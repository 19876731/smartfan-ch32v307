/**
 ******************************************************************************
 * @file    bsp_key.h
 * @brief   按键驱动（带软件消抖），4 个按键：开关 / 档位+ / 档位− / 模式
 * @note    接法：按键一端接 IO 口，另一端接 GND。
 *          内部上拉，松开时读到高电平(1)，按下时读到低电平(0)。
 *          ★不需要外接上拉电阻★
 ******************************************************************************
 */
#ifndef __BSP_KEY_H
#define __BSP_KEY_H

#include "ch32v30x.h"

/* 按键编号（位掩码，可以用 | 组合） */
#define KEY_ID_POWER    0x01u    /* 开 / 关 */
#define KEY_ID_UP       0x02u    /* 档位 + */
#define KEY_ID_DOWN     0x04u    /* 档位 − */
#define KEY_ID_MODE     0x08u    /* 手动 / 自动 切换 */

/* 消抖需要连续多少次采样到低电平才算真按下
 * 每 10ms 采一次 × 2 = 20ms，足够盖住机械按键的抖动 */
#define KEY_DEBOUNCE_CNT   2u

void    Key_Init(void);
/**
 * @brief  扫描按键，返回"本次刚刚按下"的按键位掩码
 * @note   ★每 10ms 调用一次★
 *         只在按下的那一瞬间返回一次（边沿触发），长按不会连续触发。
 *         返回值示例：KEY_ID_UP 表示档位+被按下了；0 表示没有新按键。
 */
uint8_t Key_Scan(void);

#endif /* __BSP_KEY_H */
