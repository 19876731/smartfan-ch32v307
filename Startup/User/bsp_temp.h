/**
 ******************************************************************************
 * @file    bsp_temp.h
 * @brief   LM35 温度采集（走 ADC，无需任何通信时序协议）
 *
 * 【为什么选 LM35 而不是 DS18B20 / DHT11】
 *   DS18B20 用"单总线"协议，DHT11 用自定义时序，两者都要求微秒级精确延时，
 *   零基础最容易卡在"读数全是 0 或全是 85"上，排查极其痛苦。
 *   LM35 只输出一个模拟电压（10mV = 1℃），单片机用 ADC 直接读电压就行，
 *   没有时序、没有协议、没有上拉电阻 —— 稳定性最高、资料最多。
 *
 * 【接线】LM35 三个脚（平面朝自己，从左到右）：
 *   1 = Vs   → 开发板 5V  ★必须 5V！LM35 最低工作电压是 4V，接 3.3V 不工作★
 *   2 = Vout → 开发板 PA1（ADC1 通道1）
 *   3 = GND  → 开发板 GND（与板子共地）
 ******************************************************************************
 */
#ifndef __BSP_TEMP_H
#define __BSP_TEMP_H

#include "ch32v30x.h"

void  Temp_Init(void);

/**
 * @brief  采集一次温度（内部取 5 次采样做中值滤波）
 * @retval 摄氏温度，如 26.5
 * @note   ★每 500ms 调用一次★，不要太频繁（一次约耗时几毫秒）
 */
float Temp_Update(void);

float Temp_Get(void);       /* 读最近一次滤波后的温度，不触发采样 */
uint16_t Temp_GetRaw(void); /* 读最近一次的原始 ADC 值，调试用 */

#endif /* __BSP_TEMP_H */
